<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Model;

class WalletTransaction extends Model
{
    protected $fillable = [

        /*
        |--------------------------------------------------------------------------
        | Users
        |--------------------------------------------------------------------------
        */

        'user_id',

        'receiver_id',

        /*
        |--------------------------------------------------------------------------
        | Transaction
        |--------------------------------------------------------------------------
        */

        'amount',

        'type',

        'transaction_type',

        /*
        |--------------------------------------------------------------------------
        | Service Reference
        |--------------------------------------------------------------------------
        */

        'service_type',

        'service_id',

        'reference_no',

        /*
        |--------------------------------------------------------------------------
        | Remarks
        |--------------------------------------------------------------------------
        */

        'remark',

        'remarks',

    ];

    protected $casts = [

        'amount' => 'decimal:2',

    ];

    /*
    |--------------------------------------------------------------------------
    | Transaction Types
    |--------------------------------------------------------------------------
    */

    const TYPE_CREDIT = 'credit';

    const TYPE_DEBIT = 'debit';

    const TXN_SERVICE_COMMISSION = 'service_commission';

    const TXN_REVERSE = 'reverse';

    /*
    |--------------------------------------------------------------------------
    | User
    |--------------------------------------------------------------------------
    */

    public function user()
    {
        return $this->belongsTo(User::class);
    }

    /*
    |--------------------------------------------------------------------------
    | Receiver
    |--------------------------------------------------------------------------
    */

    public function receiver()
    {
        return $this->belongsTo(User::class, 'receiver_id');
    }
}